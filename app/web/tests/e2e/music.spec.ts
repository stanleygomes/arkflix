import type { Page } from '@playwright/test'
import { axe, expect, open, test, you, type App } from './fixtures'

const call = async (page: Page, app: App, m: string, args: unknown[] = []) => {
  const res = await page.request.post(`${app.url}/api/call/${m}`, { data: args, headers: { 'X-Arkflix': '1' } })
  const body = await res.json()
  return { ok: res.ok(), result: body.result, error: body.error as string }
}

/** Vincula o Navidrome falso pelo formulário do perfil (Contas vinculadas). */
async function linkByForm(page: Page, app: App) {
  await page.locator('[data-section="music"]').click()
  await page.getByRole('button', { name: 'Vincular conta de músicas' }).click()
  const acc = page.locator('[data-account="music"]')
  await expect(acc).toBeVisible()
  await acc.getByRole('button', { name: /^Servidor de músicas/ }).click()
  await page.getByRole('dialog', { name: 'Endereço do Navidrome' }).getByLabel('Endereço do Navidrome').fill(`${app.url}/fake-navidrome`)
  await page.keyboard.press('Enter')
  await acc.getByRole('button', { name: /^Conta de músicas/ }).click()
  await page.getByRole('dialog', { name: 'Usuário do Navidrome' }).getByLabel('Usuário do Navidrome').fill('stanley')
  await page.keyboard.press('Enter')
  await acc.getByRole('button', { name: 'Conectar músicas' }).click()
  return acc
}

/** Vincula pela API (testes que não são do formulário). */
async function link(page: Page, app: App, profile = 'main', user = 'stanley', base = `${app.url}/fake-navidrome`) {
  const r = await call(page, app, 'ConnectMusic', [profile, base, user, 'senha123', ''])
  expect(r.ok, r.error).toBeTruthy()
}

